/* Aplicar traducciones */
function setLanguage(lang) {
  if (!translations[lang]) lang = 'ca';
  const t = translations[lang];
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt');
    if (t[key] !== undefined) {
      el.setAttribute('alt', t[key]);
    }
  });

  // Actualizar botón de idioma
  const current = document.getElementById('lang-current');
  if (current) current.textContent = lang.toUpperCase();

  // Marcar opción seleccionada
  document.querySelectorAll('#lang-menu [role="option"]').forEach((opt) => {
    opt.setAttribute('aria-selected', opt.getAttribute('data-lang') === lang ? 'true' : 'false');
  });

  try {
    localStorage.setItem('emt-lang', lang);
  } catch (e) { /* ignore */ }
}

function initI18n() {
  let lang = 'ca';
  try {
    const saved = localStorage.getItem('emt-lang');
    if (saved && translations[saved]) lang = saved;
    else {
      const browser = (navigator.language || 'ca').slice(0, 2).toLowerCase();
      if (translations[browser]) lang = browser;
    }
  } catch (e) { /* ignore */ }

  setLanguage(lang);

  // Selector de idioma
  const btn = document.getElementById('lang-btn');
  const menu = document.getElementById('lang-menu');
  if (!btn || !menu) return;

  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    const open = menu.hidden;
    menu.hidden = !open;
    btn.setAttribute('aria-expanded', open ? 'true' : 'false');
  });

  menu.querySelectorAll('[role="option"]').forEach((opt) => {
    opt.addEventListener('click', () => {
      setLanguage(opt.getAttribute('data-lang'));
      menu.hidden = true;
      btn.setAttribute('aria-expanded', 'false');
    });
  });

  document.addEventListener('click', () => {
    menu.hidden = true;
    btn.setAttribute('aria-expanded', 'false');
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      menu.hidden = true;
      btn.setAttribute('aria-expanded', 'false');
    }
  });
}

document.addEventListener('DOMContentLoaded', initI18n);
